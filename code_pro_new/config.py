# =============================================================================
# [4] 钻取导航 · 时间窗口    (navigation.py)
# =============================================================================

# 背离锚点钻取时，以 peak_iso 为中心向前展示的 K 线根数。
# 185 根提供足够的历史上下文（约 2 个完整波段），让用户看清背离结构。
DIVERGENCE_DRILL_BARS_BEFORE: int = 185

# 背离锚点钻取时，向后展示的 K 线根数。
# 下限约束：AFTER × next_iv_min ≥ (s3_end - peak) + 1 个父级 K 线时长
#   最坏情况：daily 父级 + 30m 子级，s3_end-peak ≈ 1 天 → 需求 AFTER ≥ 96
#   4h 父级 + 1h 子级 → 需求 AFTER ≥ 12
#   100 压住 96 这条线（裕量 4 根），不可再往下调。
DIVERGENCE_DRILL_BARS_AFTER: int = 100

# 钻取窗口"自适应扩展"的硬上限（根数）。
# 当父级 S3 段在子级别上的物理时长超过默认 286 根（BEFORE+1+AFTER）时,
# 钻取窗口会自动扩展去包住完整投影区,让低级别图能完整显示高级别 S3 范围。
#
# 若扩展后超过此上限,采用以下截断规则（保证 peak 可见 + 前侧历史优先）:
#   1. peak 之后保留默认 AFTER (100) 根 —— 信号验证窗口不丢
#   2. peak 之前最多保留 (MAX - AFTER) = 700 根 —— 前侧历史尽量扩展
#   3. 窗口总长 = MAX 根,peak 落在窗口约 87.5% 位置(末段最后 100 根之前)
#
# 800 根的考量：
#   - 14 寸图上每根仍有 ~17px 宽,蜡烛形态清晰可辨
#   - stock 1h × 800 根 ≈ 360 个交易日,远未触及 yfinance 730 天硬墙
#   - crypto 15m × 800 根 = 200 小时 ≈ 8.3 天,对极端高 S3 而言已尽力
DIVERGENCE_DRILL_BARS_MAX: int = 800


