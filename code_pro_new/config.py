# find_missed_extremes 的过短反向段过滤阈值。
#
# 动机：hist 在零轴附近的微小抖动会切出 1-3 根的短段，相邻短段之间几乎
# 必然满足"后段低点 ≤ 前段低点"的几何条件（趋势本身在创新极值），
# 导致噪声信号刷屏。S1、S2 任一段长度低于此阈值则跳过该对。
#
# 经验值：4 根是多数主流周期（周/日/小时）下一个动量阶段的最低有效长度。
# 你手动更新为 7 后噪声明显减少——如需进一步调整，改这一行即可。
# 仅影响 find_missed_extremes；标准三段背离的 min_bars 参数独立控制。
